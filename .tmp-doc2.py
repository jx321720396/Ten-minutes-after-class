import os

W = r"D:\下课十分钟"

def rw(rel):
    p = os.path.join(W, rel)
    return p, open(p, encoding="utf-8", newline="").read()

def save(p, t):
    open(p, "w", encoding="utf-8", newline="").write(t)

def rep(t, old, new, label):
    if old not in t:
        print("  !! 未匹配[%s]" % label)
        return t
    print("  ok:", label)
    return t.replace(old, new, 1)

